/*
 *    Hold the data generated by the interrupt.
 */
char _rxData[2];

/*
 *    Hold the accumulated data incoming from the UART.
 */
#define RX_BUFFER_CAPACITY 1000
char _rxBuffer[RX_BUFFER_CAPACITY];

/*
 *    Location of the next character in the accumulated buffer.
 */
uint8_t _rxIndex = 0;

/*
 *    Process data on the UARTs.
 */
void HAL_UART_RxCpltCallback(UART_HandleTypeDef *huart)
{
  if (huart->Instance == INCOMING_COM_PORT.Instance)
  {
    if (_rxIndex < RX_BUFFER_CAPACITY)
    {
      _rxBuffer[_rxIndex++] = _rxData[0];
    }
    HAL_UART_Receive_IT(&INCOMING_COM_PORT, (uint8_t *)_rxData, 1);
  }  
}

